// Helper to create Wine MenuItems with optional Bottle & Glass variations
function wine(
  id: string,
  name: string,
  region: string,
  category: string,
  bottlePrice: number,
  glassPrice?: number,
  extra?: Partial<MenuItem>,
): MenuItem {
  const variations: ItemVariation[] | undefined = glassPrice
    ? [
        { size: "Bottle", price: bottlePrice },
        { size: "Glass", price: glassPrice },
      ]
    : [{ size: "Bottle", price: bottlePrice }];
  return {
    id,
    name,
    description: glassPrice
      ? `${category} · ${region}. Available by the bottle (N$ ${bottlePrice}) or glass (N$ ${glassPrice}).`
      : `${category} · ${region}. Available by the bottle (N$ ${bottlePrice}).`,
    price: bottlePrice,
    image: dishCocktail,
    category,
    menuSection: "drinks",
    region,
    variations,
    ...extra,
  };
}

